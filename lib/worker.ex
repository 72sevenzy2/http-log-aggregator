defmodule Worker do
  @moduledoc """
  Holds needed utilities for concurrent-workers inorder for parsing chunks of logs and aggregated summaries.
  """

  @doc """
  process_chunk() takes in a list of log information and parses them via HttpLogAnalyser.parse_line(), and afterwards, returns an aggregated log summary.

  ## Examples
  ...> iex>Worker.process_chunk([
  ...>  ~s(127.0.0.1 - - [27/Oct/2026:10:00:00 +0000] "GET /api/tasks HTTP/1.1" 200 512),
  ...>  ~s(192.168.1.5 - - [27/Oct/2026:10:00:02 +0000] "GET /api/users HTTP/1.1" 404 64)
  ...> ])
  %{
    total_requests: 5,
    total_bytes: 736,
    failed_requests: 2,
    invalid_formats: 0,
    endpoint_stats: %{
      "/api/tasks" => %{
        requests: 3,
        errors: 1,
        bytes: 672
      },
      "/api/users" => %{
        requests: 1,
        errors: 1,
        bytes: 64
      },
      "/api/tasks/1" => %{
        requests: 1,
        errors: 0,
        bytes: 0
      }
    }
  }
  """
  def process_chunk(logs) do
    logs
    |> Enum.map(&HttpLogAnalyser.parse_line/1)
    |> HttpLogAnalyser.aggregate_log()
  end

  @doc """
  merge_stats() takes 2 aggregated summaries generated by workers and merges them, and returns the result afterward.

  ## Examples
  iex> Worker.merge_stats(
  ...>   %{
  ...>     total_requests: 5,
  ...>     total_bytes: 160,
  ...>     failed_requests: 2,
  ...>     invalid_formats: 0,
  ...>     endpoint_stats: %{
  ...>       "/api/tasks" => %{requests: 3, errors: 1, bytes: 10}
  ...>     }
  ...>   },
  ...>   %{
  ...>     total_requests: 5,
  ...>     total_bytes: 19,
  ...>     failed_requests: 2,
  ...>     invalid_formats: 0,
  ...>     endpoint_stats: %{
  ...>       "/api/tasks" => %{requests: 3, errors: 1, bytes: 10}
  ...>     }
  ...>   }
  ...> )
  %{
     total_requests: 10, 
     total_bytes: 179,   
     failed_requests: 4,
     invalid_formats: 0,
     endpoint_stats: %{     
       "/api/tasks" => %{     
         requests: 6,
         errors: 2,
         bytes: 20     
       },   
     }
  }

  """
  def merge_stats(l, r) do
    endpoint_stats =
      Map.merge(l.endpoint_stats, r.endpoint_stats, fn _endpoint, l, r ->
        %{
          requests: l.requests + r.requests,
          errors: l.errors + r.errors,
          bytes: l.bytes + r.bytes
        }
      end)

    %{
      l
      | total_requests: r.total_requests + l.total_requests,
        total_bytes: r.total_bytes + l.total_bytes,
        failed_requests: r.failed_requests + l.failed_requests,
        invalid_formats: r.invalid_formats + l.invalid_formats,
        endpoint_stats: endpoint_stats
    }
  end

  @doc """
  aggregate_file() takes in a log file path, and opts such as :chunk_size/:max_concurrency, to which it then creates workers to parse of the logs in chunks (default chunk size being 1000), collects the aggregated summaries of the workers to which it then gets combined and then is returned.

  ## Examples
  ...>  iex>Worker.aggregate_file("test/testLogs.log")
  {:ok,
    %{
      total_requests: 5,
      total_bytes: 736,
      failed_requests: 2,
      invalid_formats: 0,
      endpoint_stats: %{
         "/api/tasks" => %{
           requests: 3,
           errors: 1,
           bytes: 672
         },
         "/api/users" => %{
           requests: 1,
           errors: 1,
           bytes: 64
         },
         "/api/tasks/1" => %{
           requests: 1,
           errors: 0,
           bytes: 0
         }
      }
    }}
  """
  def aggregate_file(path, opts \\ []) do
    max_concurrency = Keyword.get(opts, :max_concurrency, System.schedulers_online())
    chunk_size = Keyword.get(opts, :chunk_size, 1_000)
    validate_opts(max_concurrency, chunk_size)

    try do
      path
      |> File.stream!()
      |> Stream.chunk_every(chunk_size)
      |> Task.async_stream(
        &process_chunk/1,
        max_concurrency: max_concurrency,
        ordered: false,
        timeout: 30_000,
        on_timeout: :kill_task
      )
      |> Enum.reduce_while(
        {:ok, HttpLogAnalyser.aggregate_log([])},
        fn
          {:ok, chunk_stats}, {:ok, acc} ->
            {:cont, {:ok, merge_stats(acc, chunk_stats)}}

          {:exit, :timeout}, _acc ->
            {:halt, {:error, :worker_timeout}}

          {:exit, reason}, _acc ->
            {:halt, {:error, {:worker_failed, reason}}}
        end
      )
    rescue
      e in File.Error ->
        {:error, e.reason}
    end
  end

  # validates the opts passed in aggregate_file().
  defp validate_opts(max_concurrency, chunk_size) do
    cond do
      not (is_integer(chunk_size) and chunk_size > 0) ->
        {:error, :invalid_chunk_size}

      not (is_integer(max_concurrency) and max_concurrency > 0) ->
        {:error, :invalid_max_concurrency}

      true ->
        :ok
    end
  end
end
